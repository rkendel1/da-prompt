// Publishing a GitHub-backed run: push the run branch, then open (or reuse) a pull request.
//
// Git operations (clone/push, via src/gitutil.js) and GitHub REST operations (pull requests, below)
// are deliberately separate. The REST surface is two endpoints behind GITHUB_TOKEN, the credential the
// factory already uses for pushing; it is isolated here so a shared GitHub capability package could be
// substituted in one place. Rules: only the run branch is pushed, never forced, never to the base or
// default branch; every step is idempotent so a retry reuses the branch and the pull request.

import { runGit, explainGitError } from './gitutil.js';
import { verifyIntegrity, runBranch, commitChanges } from './project.js';
import { redact } from './security.js';

export function apiBase(cfg, host) {
  if (cfg.githubApiUrl) return cfg.githubApiUrl.replace(/\/+$/, '');
  return host === 'github.com' ? 'https://api.github.com' : `https://${host}/api/v3`;
}

async function gh(cfg, repo, method, route, body, fetchImpl = fetch) {
  const res = await fetchImpl(`${apiBase(cfg, repo.host)}${route}`, {
    method,
    headers: {
      authorization: `Bearer ${cfg.githubToken}`,
      accept: 'application/vnd.github+json',
      'x-github-api-version': '2022-11-28',
      'user-agent': 'da-prompt-factory',
      ...(body ? { 'content-type': 'application/json' } : {}),
    },
    body: body ? JSON.stringify(body) : undefined,
    signal: AbortSignal.timeout(30_000),
  });
  const text = await res.text();
  let data = null;
  try {
    data = text ? JSON.parse(text) : null;
  } catch {
    /* non-JSON error page */
  }
  return { status: res.status, ok: res.ok, data, text };
}

function apiProblem(r, what) {
  const msg = redact(String(r.data?.message || r.text || '').slice(0, 300));
  if (r.status === 401) return `${what}: GitHub rejected the token (401). Check GITHUB_TOKEN.`;
  if (r.status === 403) return `${what}: forbidden (403) — the token needs pull request write access on this repository${msg ? ` (${msg})` : ''}.`;
  if (r.status === 404) return `${what}: repository or branch not found (404) — the token may lack access to it.`;
  if (r.status === 422) return `${what}: GitHub refused it (422)${r.data?.errors?.[0]?.message ? `: ${redact(r.data.errors[0].message)}` : msg ? `: ${msg}` : ''}.`;
  return `${what}: GitHub returned ${r.status}${msg ? ` — ${msg}` : ''}.`;
}

/** Plain-text summary of the run for the pull request description. */
export function buildPrBody(run, { changes, verification } = {}) {
  const p = run.plan;
  const L = [`## Goal`, '', run.inputs.idea, ''];
  if (p?.product?.summary) L.push('## Implementation', '', p.product.summary, '');
  if (changes?.files?.length) L.push('## Changes', '', ...changes.files.slice(0, 40).map((f) => `- \`${f.status}\` ${f.path} (+${f.additions}/-${f.deletions})`), changes.files.length > 40 ? `- …and ${changes.files.length - 40} more` : '', '');
  L.push('## Verification', '');
  for (const v of run.finalVerification || []) L.push(`- ${v.ok ? '✅' : '❌'} \`${v.command}\` — ${v.state || (v.ok ? 'passed' : 'failed')}`);
  if (!(run.finalVerification || []).length) L.push('- No verification commands could be run.');
  const base = (run.project?.baseline || []).filter((b) => b.status !== 'passed');
  if (base.length) L.push('', '## Baseline (before this change)', '', ...base.map((b) => `- \`${b.command}\` was already **${b.status}**${b.limitation ? ` (${b.limitation})` : ''}`));
  const open = (p?.tasks || []).filter((t) => t.status !== 'completed' && t.status !== 'skipped');
  const fails = (run.checklist || []).filter((c) => !c.ok);
  if (open.length || fails.length) L.push('', '## Outstanding', '', ...open.map((t) => `- Task \`${t.id}\` ${t.status}${t.error ? `: ${t.error}` : ''}`), ...fails.map((c) => `- ${c.label}${c.detail ? ` — ${c.detail}` : ''}`));
  if (verification) L.push('', `_Verification: ${verification}_`);
  L.push('', '_Generated by the da-prompt software factory. Review before merging._');
  return L.join('\n');
}

/**
 * Push the run branch and open a pull request. Returns the publication record to persist;
 * it never throws for expected failures and never reports success for a step that did not happen.
 */
export async function publishRun(cfg, run, { wsDir, signal, pullRequest = true, draft, fetchImpl, prBody, prTitle } = {}) {
  const src = run.source;
  const record = { ...(run.delivery?.publication || {}), attemptedAt: new Date().toISOString() };
  const fail = (step, error) => ({ ...record, state: 'failed', step, error: redact(error) });
  if (src.mode !== 'github') return fail('guard', 'only GitHub-backed runs can be published; local runs are delivered as a patch');
  if (!cfg.githubToken) return fail('guard', 'GITHUB_TOKEN is not configured on the server, so nothing can be pushed. The patch and archive are still available.');
  const branch = runBranch(run);
  if (src.branch !== branch || !/^da-prompt\/[0-9a-z-]+$/i.test(branch) || branch === src.baseBranch || branch === src.defaultBranch) {
    return fail('guard', `refusing to publish: ${branch} is not a dedicated run branch`);
  }
  const integrity = await verifyIntegrity(cfg, run, wsDir);
  if (!integrity.ok) return fail('integrity', `source protection check failed: ${integrity.problems.join('; ')}`);

  const committed = await commitChanges(cfg, run, wsDir, prTitle || `da-prompt: ${run.title}`).catch((e) => ({ error: e.message }));
  if (committed.error) return fail('commit', committed.error);
  if (!committed.commits) return { ...record, state: 'nothing-to-publish', branch, error: undefined };

  const auth = { token: cfg.githubToken, urlPrefix: `https://${src.repo.host}/` };
  const url = src.repoUrl;
  const o = { cwd: wsDir, cfg, auth, signal, timeoutMs: 300_000 };

  // Push (idempotent): skip when the remote branch already points at this commit.
  const remote = await runGit(['ls-remote', url, `refs/heads/${branch}`], o);
  if (remote.code !== 0) return fail('push', explainGitError(remote, 'Checking the remote branch').message);
  const remoteSha = remote.stdout.split('\t')[0]?.trim();
  if (remoteSha !== committed.sha) {
    const push = await runGit(['push', '--quiet', '--no-verify', url, `refs/heads/${branch}:refs/heads/${branch}`], o);
    if (push.code !== 0) {
      const text = `${push.stderr}${push.stdout}`;
      if (/non-fast-forward|rejected|fetch first/i.test(text)) return fail('push', `the remote already has a different ${branch}; it was not overwritten (no force pushes). Delete or rename that branch and publish again.`);
      if (/protected branch|GH006|403|Permission.*denied|denied to/i.test(text)) return fail('push', `GitHub refused the push to ${branch}: the token needs write access to ${src.label}. The patch and archive are still available.`);
      return fail('push', explainGitError(push, 'Pushing the run branch').message);
    }
    record.pushedAt = new Date().toISOString();
  }
  Object.assign(record, { state: 'pushed', branch, sha: committed.sha, error: undefined, step: undefined, remoteUrl: src.repo.webUrl });
  if (!pullRequest) return record;

  // Pull request (idempotent): reuse an open PR from this branch.
  if (!src.baseBranch) return { ...record, state: 'pushed', prError: `a pull request needs a branch to target; the selected ref is a ${src.baseKind}. The branch was pushed.` };
  const repo = { host: src.repo.host, owner: src.repo.owner, name: src.repo.name };
  try {
    const existing = await gh(cfg, repo, 'GET', `/repos/${repo.owner}/${repo.name}/pulls?state=open&head=${encodeURIComponent(`${repo.owner}:${branch}`)}`, null, fetchImpl);
    if (!existing.ok) return { ...record, prError: apiProblem(existing, 'Looking for an existing pull request') };
    let pr = Array.isArray(existing.data) ? existing.data.find((x) => x.head?.ref === branch) : null;
    let reused = Boolean(pr);
    if (!pr) {
      const created = await gh(cfg, repo, 'POST', `/repos/${repo.owner}/${repo.name}/pulls`, {
        title: (prTitle || run.title).slice(0, 250),
        head: branch,
        base: src.baseBranch,
        body: prBody || buildPrBody(run),
        draft: Boolean(draft),
        maintainer_can_modify: true,
      }, fetchImpl);
      if (!created.ok) return { ...record, prError: apiProblem(created, 'Opening the pull request') };
      pr = created.data;
      reused = false;
    }
    return { ...record, state: reused ? 'pr-exists' : 'pr-created', pr: { number: pr.number, url: pr.html_url, draft: Boolean(pr.draft), base: src.baseBranch, reused }, prError: undefined };
  } catch (err) {
    return { ...record, prError: `Opening the pull request failed: ${redact(err.message)}. The branch was pushed.` };
  }
}
